// Focused acceptance regression. Owned browser and mock binding, no Native/account.
import assert from 'node:assert/strict';
import { mkdir, cp, writeFile } from 'node:fs/promises';
import { resolve } from 'node:path';
import { pathToFileURL } from 'node:url';
import { chromium } from 'playwright-core';
import { markRange } from './page-fixture.mjs';

const root = resolve(process.argv[2]);
await mkdir(root);
for (const [from, name] of [[process.argv[3], 'source.mp4'], ['browser-extension/dist/page.js', 'page.js'], ['browser-extension/dist/page.css', 'page.css']]) await cp(resolve(from), root + '/' + name);
await cp(new URL(import.meta.url), root + '/executed-script.mjs');
await writeFile(root + '/fixture.html', '<!doctype html><link rel="stylesheet" href="page.css"><style>body{margin:0}.bpx-player-container{position:relative;width:min(800px,100vw);aspect-ratio:16/9;margin:50px auto}video{width:100%;height:100%}</style><div class="bpx-player-container"><video src="source.mp4"></video></div>');
const report = { scope:'owned headless Edge, local 8s media, mock binding; no Native or real site', checks:{} };
const context = await chromium.launchPersistentContext(root + '/profile', { executablePath:process.argv[4], headless:true, locale:'en-US', viewport:{ width:320, height:780 }, args:['--disable-extensions','--no-first-run','--no-default-browser-check'] });
try {
  const page = await context.newPage();
  await page.route('**/*', route => route.request().url().startsWith('file:') ? route.continue() : route.abort());
  await page.goto(pathToFileURL(root + '/fixture.html').href);
  await page.waitForFunction(() => document.querySelector('video').readyState >= 2);
  await page.evaluate(() => { globalThis.chrome = { runtime:{ onMessage:{ addListener(){}, removeListener(){} }, sendMessage:async () => ({ ok:true, value:{ key:'owned', url:'https://www.bilibili.com/video/BV17x411w7KC/', duration:document.querySelector('video').duration } }) } }; });
  await page.addScriptTag({ path:root + '/page.js' });
  await page.locator('ameow-page-tools').waitFor();
  await page.evaluate(() => ameowPageTools.openPeek());
  await page.locator('.ameow-peek[data-transition]').waitFor({ state:'detached' });
  const controls = page.locator('ameow-peek-controls'), help = controls.getByRole('button', { name:'Keyboard shortcuts', exact:true });
  report.narrow = await controls.evaluate(h => ({ width:h.clientWidth, scroll:h.shadowRoot.querySelector('.controls').scrollWidth }));
  assert(report.narrow.scroll <= report.narrow.width);
  await help.click();
  const panel = controls.getByRole('dialog', { name:'Keyboard shortcuts', exact:true });
  await panel.waitFor();
  const bounds = await panel.boundingBox();
  assert(bounds.x >= 12 && bounds.x + bounds.width <= 308 && bounds.y >= 12 && bounds.y + bounds.height <= 768);
  await page.screenshot({ path:root + '/english-320-help-light.png' });
  await page.emulateMedia({ colorScheme:'dark' });
  await page.screenshot({ path:root + '/english-320-help-dark.png' });
  await page.keyboard.press('Escape');
  assert(await help.evaluate(e => e === e.getRootNode().activeElement));
  report.checks.englishNarrowHelpFits = true;
  await page.setViewportSize({ width:848, height:780 });
  await markRange(page, 3.5, 4.5);
  await controls.locator('[data-action=view]').click();
  const window = await page.evaluate(() => ameowPageTools.timeWindow());
  assert(window.start > 0 && window.end < 8);
  const track = controls.locator('.track'), box = await track.boundingBox();
  await page.mouse.click(box.x + box.width * .25, box.y + 2);
  assert(Math.abs(await page.evaluate(() => ameowPageTools.video.currentTime) - (window.start + window.span * .25)) < .01);
  await page.mouse.down();
  await page.mouse.move(box.x + box.width + 30, box.y + 2, { steps:4 });
  assert(Math.abs(await page.evaluate(() => ameowPageTools.video.currentTime) - window.end) < .01);
  await page.mouse.up();
  assert.deepEqual(await page.evaluate(() => ameowPageTools.draft), { start_ms:3500, end_ms:4500 });
  report.checks.focusedRulerMappingAndCapture = true;
  await page.mouse.move(box.x + box.width * .5, box.y + 2);
  await page.mouse.down();
  await track.dispatchEvent('pointercancel', { pointerId:1 });
  assert.equal(await page.evaluate(() => ameowPageTools.draggingTrack), false);
  await page.mouse.up();
  report.checks.rulerPointerCancelSettles = true;
  const precise = controls.locator('[data-action=precise]');
  await page.keyboard.press('KeyI');
  const seekOutline = await controls.locator('.track input').evaluate(e => getComputedStyle(e).outlineStyle);
  assert.equal(seekOutline, 'none', 'I/O must not draw a full-width focus box around the seek input');
  await page.locator('.ameow-peek').screenshot({ path:root + '/keyboard-marker-focus.png' });
  report.checks.seekFocusStaysAtPlayhead = true;
  const tip = await precise.evaluate(e => ({ offset:getComputedStyle(e, '::after').bottom, height:e.clientHeight }));
  assert.equal(parseFloat(tip.offset), tip.height + 6);
  await precise.hover();
  await page.waitForTimeout(100);
  await page.locator('.ameow-peek').screenshot({ path:root + '/focused-tooltip-dark.png' });
  report.checks.tooltipAnchoredSixPixels = true;
  await page.mouse.move(box.x + box.width * .5, box.y + 2);
  await page.mouse.down();
  await page.keyboard.press('Escape');
  await page.mouse.up();
  await page.locator('.ameow-peek').waitFor({ state:'detached' });
  assert.equal(await page.evaluate(() => ameowPageTools.draggingTrack), false);
  report.checks.escapeRulerDragSettles = true;
  const toolbar = page.locator('ameow-page-tools');
  await toolbar.locator('[data-action=peek]').focus();
  await page.keyboard.press('Tab');
  assert(await toolbar.locator('[data-action=download]').evaluate(e => e === e.getRootNode().activeElement && e.matches(':focus-visible')));
  assert.equal(await toolbar.locator('.capsule').evaluate(e => getComputedStyle(e).outlineStyle), 'none', 'Focus must identify the current capsule action without outlining the whole capsule');
  assert.equal(await toolbar.locator('[data-action=download]').evaluate(e => getComputedStyle(e).outlineStyle), 'solid');
  await page.emulateMedia({ colorScheme:'light' });
  await page.waitForTimeout(180);
  await toolbar.screenshot({ path:root + '/capsule-keyboard-focus-light.png' });
  await page.emulateMedia({ colorScheme:'dark' });
  await page.waitForTimeout(180);
  await toolbar.screenshot({ path:root + '/capsule-keyboard-focus-dark.png' });
  report.checks.capsuleFocusIsLocal = true;
  await page.evaluate(() => ameowPageTools.stop());
} catch (error) { report.error = error.stack; throw error; }
finally { await context.close(); await writeFile(root + '/report.json', JSON.stringify(report, null, 2)); }
console.log(JSON.stringify(report, null, 2));
